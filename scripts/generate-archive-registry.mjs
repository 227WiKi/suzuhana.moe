#!/usr/bin/env node

import { mkdir, readdir, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const projectRoot = process.cwd();
const dataRoot = path.join(projectRoot, "data");
const outputFile = path.join(projectRoot, "src/generated/archive-registry.ts");

const rootFiles = ["profile.json", "timeline.json"];
const platformFiles = {
  twitter: ["user.json", "meta.json", "tweets.json", "media_map.json"],
  instagram: ["user.json", "meta.json", "posts.json"],
};

async function isFile(filename) {
  try {
    return (await stat(filename)).isFile();
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

function loaderLine(key, importPath, indent) {
  return `${" ".repeat(indent)}${JSON.stringify(key)}: () => import(${JSON.stringify(importPath)}),`;
}

async function buildMemberEntry(slug) {
  const lines = [`  ${JSON.stringify(slug)}: {`];
  let loaderCount = 0;

  for (const filename of rootFiles) {
    const absolutePath = path.join(dataRoot, slug, filename);
    if (await isFile(absolutePath)) {
      const key = filename.replace(/\.json$/, "");
      lines.push(loaderLine(key, `../../data/${slug}/${filename}`, 4));
      loaderCount += 1;
    }
  }

  for (const [platform, filenames] of Object.entries(platformFiles)) {
    const platformLines = [];
    for (const filename of filenames) {
      const absolutePath = path.join(dataRoot, slug, platform, filename);
      if (await isFile(absolutePath)) {
        const key = filename.replace(/\.json$/, "");
        platformLines.push(loaderLine(key, `../../data/${slug}/${platform}/${filename}`, 6));
        loaderCount += 1;
      }
    }
    if (platformLines.length > 0) {
      lines.push(`    ${platform}: {`, ...platformLines, "    },");
    }
  }

  lines.push("  },");
  return loaderCount > 0 ? { lines, loaderCount } : null;
}

async function main() {
  const entries = await readdir(dataRoot, { withFileTypes: true });
  const slugs = entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();

  const memberEntries = [];
  let memberCount = 0;
  let loaderCount = 0;
  for (const slug of slugs) {
    const entry = await buildMemberEntry(slug);
    if (entry) {
      memberEntries.push(...entry.lines);
      memberCount += 1;
      loaderCount += entry.loaderCount;
    }
  }

  const source = `// This file is generated by scripts/generate-archive-registry.mjs.
// Do not edit it manually; add files under data/<slug> and run npm run archive:sync.

export type ArchiveJsonLoader = () => Promise<unknown>;

export interface PlatformArchiveLoaders {
  user?: ArchiveJsonLoader;
  meta?: ArchiveJsonLoader;
  tweets?: ArchiveJsonLoader;
  media_map?: ArchiveJsonLoader;
  posts?: ArchiveJsonLoader;
}

export interface MemberArchiveLoaders {
  profile?: ArchiveJsonLoader;
  timeline?: ArchiveJsonLoader;
  twitter?: PlatformArchiveLoaders;
  instagram?: PlatformArchiveLoaders;
}

export const archiveRegistry: Record<string, MemberArchiveLoaders> = {
${memberEntries.join("\n")}
};
`;

  await mkdir(path.dirname(outputFile), { recursive: true });
  const temporaryFile = `${outputFile}.tmp`;
  await writeFile(temporaryFile, source, "utf8");
  await rename(temporaryFile, outputFile);
  console.log(`Generated archive registry for ${memberCount} members (${loaderCount} loaders).`);
}

main().catch((error) => {
  console.error(`Archive registry generation failed: ${error.message}`);
  process.exitCode = 1;
});
